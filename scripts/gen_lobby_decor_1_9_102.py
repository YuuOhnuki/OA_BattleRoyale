#!/usr/bin/env python3
"""Generates lobby decoration functions (relative to lobby origin) and hooks them into lobby/build."""
import math, sys
from pathlib import Path
root = Path(sys.argv[1]); fn = root / 'data/oa/function/lobby'
# ---- floor medallion (y=-1), written first so pads/gallery overwrite it ----
def ring(r):
    if 4.0 <= r < 5.5: return 'minecraft:polished_blackstone'
    if 5.5 <= r < 6.5: return 'minecraft:gold_block'
    if 9.0 <= r < 10.0: return 'minecraft:amethyst_block'
    if 10.0 <= r < 11.0: return 'minecraft:gold_block'
    if 14.0 <= r < 15.0: return 'minecraft:polished_blackstone'
    if 15.0 <= r < 16.0: return 'minecraft:smooth_quartz'
    return None
cells = {}
for z in range(-20, 21):
    for x in range(-20, 21):
        r = math.hypot(x, z); b = ring(r)
        if b is None and 11 <= r < 20 and (x == 0 or z == 0 or abs(abs(x) - abs(z)) <= 0 ): b = 'minecraft:gold_block' if (x == 0 or z == 0) else 'minecraft:chiseled_quartz_block'
        if b: cells[(x, z)] = b
L = ['# 1.9.102 lobby floor medallion (generated by scripts/gen_lobby_decor_1_9_102.py)']
for z in range(-20, 21):
    x = -20
    while x <= 20:
        b = cells.get((x, z))
        if not b: x += 1; continue
        x2 = x
        while x2 + 1 <= 20 and cells.get((x2 + 1, z)) == b: x2 += 1
        L.append(f'fill ~{x} ~-1 ~{z} ~{x2} ~-1 ~{z} {b}'); x = x2 + 1
(fn / 'decor_floor.mcfunction').write_text('\n'.join(L) + '\n')
# ---- structures ----
D = ['# 1.9.102 lobby decoration (generated)']
# fountain
for z in range(-3, 4):
    for x in range(-3, 4):
        r = math.hypot(x, z)
        if r <= 2.4: D.append(f'setblock ~{x} ~-1 ~{z} minecraft:water')
        elif r < 3.5:
            D.append(f'setblock ~{x} ~-1 ~{z} minecraft:smooth_quartz'); D.append(f'setblock ~{x} ~0 ~{z} minecraft:quartz_slab[type=bottom]')
D += ['setblock ~0 ~-1 ~0 minecraft:sea_lantern', 'fill ~0 ~0 ~0 ~0 ~2 ~0 minecraft:quartz_pillar', 'setblock ~0 ~3 ~0 minecraft:chiseled_quartz_block',
      'setblock ~0 ~4 ~0 minecraft:sea_lantern', 'fill ~0 ~5 ~0 ~0 ~6 ~0 minecraft:end_rod[facing=up]']
for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1)):
    D.append(f'setblock ~{dx} ~-1 ~{dz} minecraft:prismarine_bricks')
# obelisks
for sx in (-1, 1):
    for sz in (-1, 1):
        cx, cz = 16 * sx, 16 * sz
        D += [f'fill ~{cx-1} ~0 ~{cz-1} ~{cx+1} ~0 ~{cz+1} minecraft:polished_blackstone_bricks', f'fill ~{cx} ~1 ~{cz} ~{cx} ~4 ~{cz} minecraft:quartz_pillar',
              f'setblock ~{cx} ~5 ~{cz} minecraft:amethyst_block', f'setblock ~{cx} ~6 ~{cz} minecraft:sea_lantern', f'setblock ~{cx} ~7 ~{cz} minecraft:end_rod[facing=up]']
        for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            D.append(f'setblock ~{cx+dx*2} ~0 ~{cz+dz*2} minecraft:lantern[hanging=false]')
# hedges along the outer wall (inside side)
D += ['fill ~-38 ~0 ~-37 ~-38 ~0 ~37 minecraft:azalea_leaves[persistent=true]', 'fill ~-38 ~1 ~-37 ~-38 ~1 ~37 minecraft:flowering_azalea_leaves[persistent=true]',
      'fill ~38 ~0 ~-37 ~38 ~0 ~37 minecraft:azalea_leaves[persistent=true]', 'fill ~38 ~1 ~-37 ~38 ~1 ~37 minecraft:flowering_azalea_leaves[persistent=true]',
      'fill ~-37 ~0 ~-38 ~37 ~0 ~-38 minecraft:azalea_leaves[persistent=true]', 'fill ~-37 ~1 ~-38 ~37 ~1 ~-38 minecraft:flowering_azalea_leaves[persistent=true]',
      'fill ~-37 ~0 ~38 ~37 ~0 ~38 minecraft:azalea_leaves[persistent=true]', 'fill ~-37 ~1 ~38 ~37 ~1 ~38 minecraft:flowering_azalea_leaves[persistent=true]']
# pergola of beams between the 16 pillar caps + hanging lanterns
for a in (-36, -20, 20, 36):
    D.append(f'fill ~{a} ~12 ~-36 ~{a} ~12 ~36 minecraft:quartz_slab[type=top]')
    D.append(f'fill ~-36 ~12 ~{a} ~36 ~12 ~{a} minecraft:quartz_slab[type=top]')
def hang(x, z):
    return [f'fill ~{x} ~10 ~{z} ~{x} ~11 ~{z} minecraft:chain[axis=y]', f'setblock ~{x} ~9 ~{z} minecraft:lantern[hanging=true]']
pos = set()
for a in (-36, -20, 20, 36):
    for t in (-28, -14, 0, 14, 28):
        for (x, z) in ((a, t), (t, a)):
            if abs(z) == 36 and abs(x) <= 8: continue
            if abs(x) == 36 and abs(z) <= 0: pass
            pos.add((x, z))
for (x, z) in sorted(pos): D += hang(x, z)
(fn / 'decor.mcfunction').write_text('\n'.join(D) + '\n')
# ---- hook into build ----
p = fn / 'build.mcfunction'; s = p.read_text().splitlines()
if 'function oa:lobby/decor_floor' not in s:
    k = next(i for i, l in enumerate(s) if l == 'fill ~-40 ~-1 ~-40 ~40 ~-1 ~40 minecraft:smooth_quartz')
    s.insert(k + 1, 'function oa:lobby/decor_floor')
if 'function oa:lobby/decor' not in s:
    k = next(i for i, l in enumerate(s) if l == 'function oa:lobby/map_labels_build')
    s.insert(k, 'function oa:lobby/decor')
p.write_text('\n'.join(s) + '\n')
print(len(L), len(D))
