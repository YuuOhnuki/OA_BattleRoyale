def page(title, body, links):
    e = [{'text': title + '\n', 'color': 'dark_aqua', 'bold': True}, {'text': body + '\n', 'color': 'black'}]
    for label, command in links:
        e.append({'text': '▸ ' + label + '\n', 'color': 'dark_blue', 'underlined': True,
                  'click_event': {'action': 'run_command', 'command': command},
                  'hover_event': {'action': 'show_text', 'value': command}})
    check_page(e)
    return {'raw': {'text': '', 'extra': e}}

